/**
 * 组装某体系的 system + user 提示
 * @param {string} engineId
 * @param {object} o { question, panText, panData }
 */
export function buildPrompt(engineId, o) {
  const lib = PROMPT_LIB[engineId] || { name: '通用玄学', persona: '你是一位严谨的玄学研习者。' };
  const system = [
    lib.persona,
    COMMON,
    OUTLINE,
    o.question
      ? `\n【本次用户的提问】${o.question}\n请务必围绕这个提问作答，不要泛泛论命。`
      : '\n【本次用户未指定具体问题】请做整体解读，重点讲清结构与当下。',
  ].join('\n');

  const user = [
    `【体系】${lib.name}`,
    '',
    '【排盘结果（本地引擎输出，请以此为准）】',
    '```',
    o.panText || '（无）',
    '```',
    o.panData ? '\n【结构化数据（供你精确引用）】\n```json\n' + safeJson(o.panData) + '\n```' : '',
  ].join('\n');

  return { system, user };
}

/** 安全序列化：截断超大字段，避免烧 token */
function safeJson(obj, maxLen = 6000) {
  try {
    let s = JSON.stringify(obj, (k, v) => {
      if (typeof v === 'string' && v.length > 800) return v.slice(0, 800) + '…';
      return v;
    }, 1);
    if (s.length > maxLen) s = s.slice(0, maxLen) + '\n…（已截断）';
    return s;
  } catch { return '（无法序列化）'; }
}
