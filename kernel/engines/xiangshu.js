/**
 * 观相解读：传入特征标签数组，返回匹配到的传统断语
 * @param {string[]} tags 例如 ['额宽高平满','鼻高挺准头圆']
 */
export function kanXiang(tags = []) {
  const hits = [];
  for (const t of tags) {
    const found = XIANG_TIAO.filter(x => x.key.includes(t) || t.includes(x.key));
    for (const f of found) hits.push({ input: t, ...f });
  }
  const areas = [...new Set(hits.map(h => h.area))];
  const missing = tags.filter(t => !XIANG_TIAO.some(x => x.key.includes(t) || t.includes(x.key)));
  return {
    tags, hits, areas, missing,
    note: hits.length ? '' : '未匹配到内置断语；可在备注中描述，交由 AI 综合解读。',
    disclaimer: '相术属经验归纳，各派断语不同；本结果仅作传统说法的索引，不作为命运断定。',
  };
}

export function xiangshuToText(r) {
  const L = [];
  L.push(`【所观特征】${r.tags.join('、') || '（未选）'}`);
  L.push('');
  if (r.hits.length) {
    L.push('【逐条断语】');
    for (const h of r.hits) L.push(`　· ${h.input}（${h.area}）：${h.text}`);
  } else {
    L.push(`【提示】${r.note}`);
  }
  if (r.missing.length) L.push(`\n【未收录特征】${r.missing.join('、')}`);
  L.push('');
  L.push('【十二宫参考】');
  for (const g of SHI_ER_GONG) L.push(`　${g.name}（${g.pos}）主${g.zhu}｜吉：${g.ji}｜忌：${g.ji2}`);
  L.push('');
  L.push(`【声明】${r.disclaimer}`);
  return L.join('\n');
}
