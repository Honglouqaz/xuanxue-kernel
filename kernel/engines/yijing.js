/** 由上下卦名取六十四卦 */
export const gua64ByName = (up, down) => GUA_64.find(g => g[2] === up && g[3] === down) || null;
/** findGua(上卦, 下卦)，如 findGua('乾','坤') = 天地否 */
export const findGua = gua64ByName;

/** 三爻（自下而上，1=阳）→ 八卦名 */
const YAO_TO_GUA = { '111': '乾', '110': '兑', '101': '离', '100': '震', '011': '巽', '010': '坎', '001': '艮', '000': '坤' };
export const yaoToGuaName = (y) => YAO_TO_GUA[y.join('')];

/** 六爻（自下而上，1=阳）→ 本卦 / 互卦 / 错卦 / 综卦 */
export function jieGua(yao) {
  const mk = (arr) => findGua(yaoToGuaName(arr.slice(3, 6)), yaoToGuaName(arr.slice(0, 3)));
  const huArr = [yao[1], yao[2], yao[3], yao[2], yao[3], yao[4]];
  const cuoArr = yao.map(v => (v ? 0 : 1));
  const zongArr = [...yao].reverse();
  return {
    yao,
    ben: mk(yao),
    hu: mk(huArr),
    cuo: mk(cuoArr),
    zong: mk(zongArr),
  };
}

/** 摇卦：三枚铜钱，随机源可注入；返回六爻（自下而上） */
export function yaoGua(opt = {}) {
  const rnd = opt.rnd || Math.random;
  const yao = [];
  for (let i = 0; i < 6; i++) {
    let sum = 0;
    for (let j = 0; j < 3; j++) sum += rnd() < 0.5 ? 2 : 3;   // 字面=2 背面=3
    yao.push(sum === 7 || sum === 9 ? 1 : 0);                 // 7少阳 9老阳为阳
  }
  return yao;
}

export function yijingToText(r, question) {
  const L = [];
  const f = (g) => g ? `第${g[0]}卦　${g[1]}（上${g[2]}下${g[3]}）　【${g[5]}】\n　卦辞：${g[4]}\n　要义：${g[6]}` : '—';
  if (question) L.push(`【所问】${question}`);
  L.push(`【爻象】${r.yao.map(v => v ? '—' : '- -').join(' / ')}　（自下而上）`);
  L.push('');
  L.push('【本卦】' + f(r.ben));
  L.push('');
  L.push('【互卦】' + f(r.hu));
  L.push('');
  L.push('【错卦（旁通）】' + f(r.cuo));
  L.push('');
  L.push('【综卦（反对）】' + f(r.zong));
  return L.join('\n');
}
